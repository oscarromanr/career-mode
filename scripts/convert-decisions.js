/* Stage 6: canonical decision schema converter.
   Reads the legacy a/b/c cards in js/data.js and the options[] cards in
   js/data-decisions.js, converts EVERY card to the canonical options[]
   schema, preserves fx/mini/risk exactly, dedupes, and writes
   js/data-decisions-canonical.js as the single shipped decisions source.

   Run: node scripts/convert-decisions.js
   The canonical schema extends options[] with optional `fx` (full EffectFx)
   and `mini` so no gameplay data is lost in conversion.
*/
'use strict';
const fs = require('fs');
const path = require('path');

const DATA = require('../js/data.js');
global.GAME_DATA = DATA;
require('../js/data-decisions.js');

function toCanonical(d) {
  const out = {
    id: d.id,
    min: d.min,
    max: d.max,
  };
  if (d.pos !== undefined) out.pos = d.pos;
  if (d.rarity !== undefined) out.rarity = d.rarity;
  if (d.title) out.title = d.title;
  if (d.desc) out.desc = d.desc;
  if (d.requiresNt) out.requiresNt = true;
  if (d.requiresTournament) out.requiresTournament = true;
  if (d.kicker) out.kicker = d.kicker;

  if (Array.isArray(d.options)) {
    // Already canonical: keep as-is (options carry id/text/changes or fx).
    out.options = d.options.map((o) => {
      const opt = { id: o.id, text: o.text || o.label || o.id };
      if (o.sub) opt.sub = o.sub;
      if (o.out) opt.out = o.out;
      if (o.changes) opt.changes = o.changes;
      if (o.fx) opt.fx = o.fx;
      if (o.mini) opt.mini = o.mini;
      return opt;
    });
  } else {
    // Legacy a/b/c: convert preserving fx and mini verbatim.
    out.options = ['a', 'b', 'c']
      .filter((k) => d[k])
      .map((k) => {
        const o = d[k];
        const opt = { id: k, text: o.label || k.toUpperCase() };
        if (o.sub) opt.sub = o.sub;
        if (o.out) opt.out = o.out;
        if (o.fx) opt.fx = o.fx;
        if (o.mini) opt.mini = o.mini;
        return opt;
      });
  }
  return out;
}

const converted = DATA.DECISIONS.map(toCanonical);

// Dedupe (should be none, but guard against silent appends).
const seen = new Set();
const unique = converted.filter((d) => {
  if (seen.has(d.id)) {
    console.error(`WARN: duplicate id dropped in conversion: ${d.id}`);
    return false;
  }
  seen.add(d.id);
  return true;
});

// Verify nothing was lost: option counts must match 2+ per card.
let minOptions = Infinity;
unique.forEach((d) => { minOptions = Math.min(minOptions, d.options.length); });

const body = unique.map((d) => {
  const json = JSON.stringify(d, null, 2);
  // indent options entries for readability
  return json;
});

const header = `/* ============================================================
   CAREER MODE '26 - canonical decision cards (generated)
   ============================================================
   Generated by scripts/convert-decisions.js from js/data.js (legacy
   a/b/c) and js/data-decisions.js (options[]). Do not edit by hand;
   edit the source packs and regenerate.

   Schema:
   {
     id, min, max,
     pos?: 'any' | 'gk' | 'field' | 'att' | 'mid' | 'def' | PositionId[],
     rarity?: string,
     title, desc,
     options: [{
       id: string,           // 'a' | 'b' | 'c' | custom
       text: string,         // option label
       sub?: string,
       out?: string,         // outcome text (EN; ES in i18n)
       fx?: EffectFx,        // stats/form/hype/stam/mor/rep/loyalty/money/injury/special/risk
       mini?: MiniGame,      // penalty/timing minigame descriptor
       changes?: [{ k, d }], // legacy alternative to fx (converted by normalizer)
     }]
   }
   ============================================================ */
(function (root) {
  'use strict';

  const CANONICAL_DECISIONS = [
${body.join(',\n')}
  ];

  if (root.GAME_DATA) root.GAME_DATA.DECISIONS = CANONICAL_DECISIONS;
  if (typeof require !== 'undefined' && typeof module !== 'undefined' && module.exports) module.exports = CANONICAL_DECISIONS;
})(typeof window !== 'undefined' ? window : globalThis);
`;

fs.writeFileSync(path.join(__dirname, '..', 'js', 'data-decisions-canonical.js'), header);
console.log(`Wrote js/data-decisions-canonical.js with ${unique.length} decisions (min options per card: ${minOptions})`);
