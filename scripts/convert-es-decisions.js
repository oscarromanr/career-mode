/* Stage 6: convert flat ES decision translation keys to the nested schema.
   Old: 'gk-sweeper.title', 'gk-sweeper.optA' at I18N_ES top level.
   New: decisions['gk-sweeper'] = { title, desc, a: { label }, b: { label } }
   Run: node scripts/convert-es-decisions.js
   The runtime compatibility lookup (I18n.TData flat fallback) is removed
   once this conversion is complete. */
'use strict';
const fs = require('fs');
const path = require('path');

const DATA = require('../js/data.js');
global.GAME_DATA = DATA;
require('../js/data-decisions-canonical.js');
require('../js/i18n-es.js');
require('../js/i18n-es-decisions.js');

const ES = globalThis.I18N_ES;
const flatKeys = Object.keys(ES).filter((k) => !['headlines', 'simLines', 'retirementQuotes', 'decisions', 'boosters', 'consumables', 'releasedReasons', 'riskOutcomes'].includes(k));

const nested = {};
flatKeys.forEach((k) => {
  const m = k.match(/^(.+?)\.([^.]+)$/);
  if (!m) return;
  const id = m[1];
  const field = m[2];
  const value = ES[k];
  if (!nested[id]) nested[id] = {};
  if (field === 'title') nested[id].title = value;
  else if (field === 'desc') nested[id].desc = value;
  else if (field === 'optA') {
    nested[id].a = nested[id].a || {};
    nested[id].a.label = value;
  } else if (field === 'optB') {
    nested[id].b = nested[id].b || {};
    nested[id].b.label = value;
  } else if (field === 'optC') {
    nested[id].c = nested[id].c || {};
    nested[id].c.label = value;
  }
});

// Preserve any existing nested translations (i18n-es.js) that the flat file
// overrides; the flat file wins for fields it defines.
const EXISTING = ES.decisions || {};
Object.keys(nested).forEach((id) => {
  const merged = Object.assign({}, EXISTING[id], nested[id]);
  if (EXISTING[id] && EXISTING[id].a && !merged.a) merged.a = EXISTING[id].a;
  if (EXISTING[id] && EXISTING[id].b && !merged.b) merged.b = EXISTING[id].b;
  nested[id] = merged;
});

const entries = Object.keys(nested).sort().map((id) => {
  const d = nested[id];
  const parts = [];
  if (d.title !== undefined) parts.push(`      title: ${JSON.stringify(d.title)}`);
  if (d.desc !== undefined) parts.push(`      desc: ${JSON.stringify(d.desc)}`);
  ['a', 'b', 'c'].forEach((k) => {
    if (d[k]) {
      const opt = d[k];
      const optParts = [];
      if (opt.label !== undefined) optParts.push(`label: ${JSON.stringify(opt.label)}`);
      if (opt.sub !== undefined) optParts.push(`sub: ${JSON.stringify(opt.sub)}`);
      if (opt.out !== undefined) optParts.push(`out: ${JSON.stringify(opt.out)}`);
      parts.push(`      ${k}: { ${optParts.join(', ')} }`);
    }
  });
  return `    ${JSON.stringify(id)}: {\n${parts.join(',\n')}\n    }`;
});

const body = `/* ============================================================
   CAREER MODE '26 - Spanish decision translations (nested schema)
   ============================================================
   Generated by scripts/convert-es-decisions.js from the legacy flat
   keys ({id}.title / {id}.optA). Nested per canonical decision id:
   decisions[id] = { title, desc, a: { label, sub, out }, ... }
   Missing entries fall back to English via I18n.TData.
   ============================================================ */
(function (root) {
  'use strict';

  const ES_DECISIONS_NESTED = {
${entries.join(',\n')}
  };

  root.I18N_ES = root.I18N_ES || {};
  root.I18N_ES.decisions = Object.assign({}, root.I18N_ES.decisions, ES_DECISIONS_NESTED);
  if (typeof require !== 'undefined' && typeof module !== 'undefined' && module.exports) module.exports = ES_DECISIONS_NESTED;
})(typeof window !== 'undefined' ? window : globalThis);
`;

const out = path.join(__dirname, '..', 'js', 'i18n-es-decisions.js');
fs.writeFileSync(out, body);
console.log(`Wrote ${out} with ${Object.keys(nested).length} nested decision translations`);
